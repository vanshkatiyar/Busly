export function getSeatErgonomics(seatNumber: string): import('../types').SeatErgonomics {
  const isLower = seatNumber.startsWith('L') || (!seatNumber.startsWith('U') && !seatNumber.startsWith('UR'));
  const isUpper = seatNumber.startsWith('U') || seatNumber.startsWith('UR');
  const isWindow = seatNumber.includes('1') || seatNumber.includes('4') || seatNumber.startsWith('L');

  return {
    seatNumber,
    legroomInches: isUpper ? 40 : 37,
    legroomGrade: isUpper ? 'Spacious (38"+)' : 'Standard (34"-36")',
    reclineDegrees: 180, // Flat Sleeper Berth
    chargingScorePct: 98,
    vibrationScorePct: isLower ? 12 : 20, // Lower vibration on lower deck
    windowAlignment: isWindow ? 'Panoramic Clear View' : 'Aisle Berth',
    travelerReview: isLower
      ? 'Extremely smooth ride on the lower deck with steady USB charging throughout the night.'
      : 'Upper deck offers unmatched privacy and wide panoramic highway views at sunrise.',
    travelerRating: 4.8,
  };
}
